  if (el) el.innerHTML = '<img src="icons/check.svg" width="16" height="16" style="vertical-align:middle" /> ' + t('guardarCambios');
  el = document.querySelector('#perfil-edicion .btn-catalogo');
  if (el) el.textContent = t('cancelar');

  // Re-render current section content
  var seccionActiva = document.querySelector('.seccion.activa');
  if (seccionActiva) {
    var id = seccionActiva.id;
    // Trigger re-render for sections with dynamic content
    if (id === 'inicio') {
      actualizarInfoUsuario();
      refrescarHistorial();
      refrescarPlanSemanal();
    } else if (id === 'progreso') {
      refrescarHistorial();
    } else if (id === 'entrenar') {
      poblarSelectEjercicios();
    } else if (id === 'catalogo') {
      mostrarCatalogo();
    } else if (id === 'perfil') {
      actualizarInfoUsuario();
    }
  }
